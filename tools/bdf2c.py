#!/usr/bin/env python3
"""Convert a fixed-width BDF font to a C table of the printable ASCII
characters: per character, rows from the top, each row ceil(width / 8)
bytes with the leftmost pixel in the high bit."""
import sys

FIRST, LAST = 32, 126


def main():
    path, name = sys.argv[1], sys.argv[2]
    width = height = None
    glyphs, code, rows, in_bitmap = {}, None, [], False
    for line in open(path, encoding="latin-1"):
        words = line.split()
        if not words:
            continue
        if words[0] == "FONTBOUNDINGBOX":
            width, height = int(words[1]), int(words[2])
        elif words[0] == "ENCODING":
            code = int(words[1])
        elif words[0] == "BITMAP":
            in_bitmap, rows = True, []
        elif words[0] == "ENDCHAR":
            in_bitmap = False
            glyphs[code] = rows
        elif in_bitmap:
            rows.append(int(words[0], 16))
    row_bytes = (width + 7) // 8
    print(f"/* Generated by tools/bdf2c.py from {path.split('/')[-1]} (Spleen, BSD-2-Clause, see LICENSE). */")
    print('#include "font.h"\n')
    print(f"static const uint8_t {name}_glyphs[] = {{")
    for c in range(FIRST, LAST + 1):
        rows = glyphs.get(c, [0] * height)
        data = []
        for r in rows:
            data += [(r >> (8 * (row_bytes - 1 - k))) & 0xFF for k in range(row_bytes)]
        print("    " + ", ".join(f"0x{b:02x}" for b in data) + f",  /* {chr(c)!r} */")
    print("};\n")
    print(f"const struct font {name} = {{ {width}, {height}, {row_bytes}, {name}_glyphs }};")


if __name__ == "__main__":
    main()
